//! Self-measurement of analysis coverage: how much of the analyzed source
//! slice the engine actually understands.
//!
//! [`coverage`] runs the same machinery the semantic tier runs — file
//! parsing, the module graph, `use` target resolution, and the type graph —
//! and reports honest raw counters instead of findings: how many files
//! parsed, how many became modules reachable from a crate root, how many
//! `use` targets resolve to a workspace module, and how many structures and
//! fields the type graph captured.
//!
//! The counters deliberately do not overclaim. `derives_seen` and
//! `item_macros_seen` count occurrences only: the engine never expands
//! macros or derives, so items generated by them are invisible to every
//! other counter.

use std::collections::{BTreeMap, BTreeSet};

use syn::visit::Visit;

use super::{
    graph::TypeGraph,
    module_graph::{ModuleGraph, resolved_module}
};
use crate::source::Source;

/// Raw coverage counters of one analyzed source slice.
///
/// Every field is an absolute count; percentages are computed by the caller
/// via [`percent`] or the convenience rate methods. `files_total` counts the
/// sources handed to [`coverage`], so files skipped before that point —
/// unreadable or over the memory budget — are not represented here.
///
/// `derives_seen` and `item_macros_seen` are sightings, not understanding:
/// macro and derive expansions are not analyzed, so anything they generate
/// is absent from the module, type, and `use` counters.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Coverage {
    /// Sources in the analyzed slice.
    pub files_total:                u64,
    /// Sources accepted by the Rust parser.
    pub files_parsed:               u64,
    /// Nodes in the module graph, including single-file fallback roots and
    /// inline modules.
    pub modules_total:              u64,
    /// Distinct files that became at least one module reachable from a
    /// cargo-layout crate root (`src/lib.rs`, `src/main.rs`, `src/bin/*`,
    /// `build.rs`, top-level `tests/`, `benches/`, `examples/`).
    pub files_reachable:            u64,
    /// Distinct files claimed by no layout root and promoted to standalone
    /// crate roots of their own (compile-test fixtures, broken `mod`
    /// chains, lone reviewed files).
    pub files_standalone:           u64,
    /// Structure definitions captured by the type graph.
    pub structs_captured:           u64,
    /// Enum definitions captured by the type graph.
    pub enums_captured:             u64,
    /// Trait definitions captured by the type graph.
    pub traits_captured:            u64,
    /// Impl blocks captured by the type graph.
    pub impls_captured:             u64,
    /// Methods and associated functions captured across all impl blocks.
    pub methods_captured:           u64,
    /// Named fields captured across all structures and enum payloads.
    pub fields_captured:            u64,
    /// Fields whose type name resolved to a workspace type.
    pub aggregation_edges_resolved: u64,
    /// Type-to-type interaction edges resolved from method bodies.
    pub interaction_edges_resolved: u64,
    /// Expanded `use` targets across all modules.
    pub use_targets_total:          u64,
    /// `use` targets that resolve to a module of the same crate.
    pub use_targets_resolved:       u64,
    /// `use` targets whose leading segment names a known external crate:
    /// the standard-library family or a declared dependency.
    pub use_targets_external:       u64,
    /// `use` targets that neither resolve in-workspace nor name a known
    /// external crate — the honest "did not understand" bucket.
    pub use_targets_unresolved:     u64,
    /// `#[derive(...)]` attributes seen on items; their expansions are not
    /// analyzed.
    pub derives_seen:               u64,
    /// Item-level macro invocations seen; their expansions are not
    /// analyzed.
    pub item_macros_seen:           u64,
    /// Call candidates observed across all function bodies.
    pub call_candidates_total:      u64,
    /// Call candidates that resolved to exactly one workspace function.
    pub call_candidates_resolved:   u64,
    /// Unmatched call candidates whose owner names no workspace type or
    /// module — attributable to external code.
    pub call_candidates_external:   u64,
    /// Unmatched call candidates whose receiver type never resolved —
    /// the engine's own understanding gap.
    pub call_candidates_unknown:    u64
}

impl Coverage {
    /// Share of files the parser accepted, in percent of `files_total`.
    #[must_use]
    pub const fn parse_rate(&self) -> f64 {
        percent(self.files_parsed, self.files_total)
    }

    /// Share of `use` targets resolved in-workspace, in percent of
    /// `use_targets_total`.
    #[must_use]
    pub const fn resolution_rate(&self) -> f64 {
        percent(self.use_targets_resolved, self.use_targets_total)
    }

    /// Share of files reachable from a crate root, in percent of
    /// `files_total`.
    #[must_use]
    pub const fn reachability_rate(&self) -> f64 {
        percent(self.files_reachable, self.files_total)
    }

    /// Share of `use` targets accounted for — resolved in-workspace or
    /// attributed to a known external crate — in percent of
    /// `use_targets_total`.
    #[must_use]
    pub const fn accounted_rate(&self) -> f64 {
        percent(
            self.use_targets_resolved + self.use_targets_external,
            self.use_targets_total
        )
    }

    /// Share of call candidates that resolved to exactly one workspace
    /// function, in percent of `call_candidates_total`.
    #[must_use]
    pub const fn call_resolution_rate(&self) -> f64 {
        percent(self.call_candidates_resolved, self.call_candidates_total)
    }

    /// Share of call candidates accounted for — resolved in-workspace or
    /// attributed to external code — in percent of
    /// `call_candidates_total`.
    #[must_use]
    pub const fn call_accounted_rate(&self) -> f64 {
        percent(
            self.call_candidates_resolved + self.call_candidates_external,
            self.call_candidates_total
        )
    }
}

/// Returns `part` as a percentage of `whole`, or `0.0` when `whole` is zero.
#[must_use]
#[allow(
    clippy::cast_precision_loss,
    reason = "coverage counters stay far below 2^52, so the casts are exact"
)]
pub const fn percent(part: u64, whole: u64) -> f64 {
    if whole == 0 {
        return 0.0;
    }
    part as f64 / whole as f64 * 100.0
}

/// Measures `sources` like [`coverage_with`] with no declared
/// dependencies: only the standard-library family counts as external.
#[must_use]
pub fn coverage(sources: &[Source]) -> Coverage {
    coverage_with(sources, &BTreeSet::new())
}

/// Measures how much of `sources` the engine's parsing, module graph, and
/// type graph actually capture.
///
/// The measurement reuses the production machinery unchanged: the module
/// graph decides reachability, the `module-cycles` resolution logic decides
/// which `use` targets count as in-workspace, and the type graph provides
/// the structure counters. `use` targets that do not resolve in-workspace
/// are attributed to a known external crate — the standard-library family
/// or a name in `external_crates` — or counted as honestly unresolved.
/// Macro and derive expansions are never analyzed; they are only counted
/// as sightings.
#[must_use]
pub fn coverage_with(sources: &[Source], external_crates: &BTreeSet<String>) -> Coverage {
    let mut files_parsed = 0u64;
    let mut derives_seen = 0u64;
    let mut item_macros_seen = 0u64;
    for source in sources {
        let Ok(file) = syn::parse_file(source.text()) else {
            continue;
        };
        files_parsed += 1;
        let mut counter = MacroCounter::default();
        counter.visit_file(&file);
        derives_seen += counter.derives;
        item_macros_seen += counter.item_macros;
    }
    let graph = ModuleGraph::from_sources(sources);
    let modules = graph.modules();
    let reachable: BTreeSet<usize> = modules
        .iter()
        .filter(|module| module.layout)
        .map(|module| module.source)
        .collect();
    let standalone: BTreeSet<usize> = modules
        .iter()
        .filter(|module| !module.layout && !reachable.contains(&module.source))
        .map(|module| module.source)
        .collect();
    let mut use_targets_total = 0u64;
    let mut use_targets_resolved = 0u64;
    let mut use_targets_external = 0u64;
    let mut use_targets_unresolved = 0u64;
    for (from, module) in modules.iter().enumerate() {
        for use_target in &module.uses {
            use_targets_total += 1;
            if resolved_module(modules, from, &use_target.target).is_some() {
                use_targets_resolved += 1;
            } else if external_target(&use_target.target, external_crates) {
                use_targets_external += 1;
            } else {
                use_targets_unresolved += 1;
            }
        }
    }
    let facts = super::behavior::behavior(sources);
    let graph = super::calls::call_graph(&facts, &super::calls::resolution_segments(sources));
    let types = TypeGraph::from_sources(sources);
    let fields_captured = types
        .types()
        .iter()
        .map(|node| count(node.fields.len()))
        .sum();
    let structs_captured = types
        .types()
        .iter()
        .filter(|node| node.kind == super::graph::TypeKind::Struct)
        .count();
    let enums_captured = types.types().len() - structs_captured;
    let methods_captured = types
        .impls()
        .iter()
        .map(|node| count(node.methods.len()))
        .sum();
    Coverage {
        files_total: count(sources.len()),
        files_parsed,
        modules_total: count(modules.len()),
        files_reachable: count(reachable.len()),
        files_standalone: count(standalone.len()),
        structs_captured: count(structs_captured),
        enums_captured: count(enums_captured),
        traits_captured: count(types.traits().len()),
        impls_captured: count(types.impls().len()),
        methods_captured,
        fields_captured,
        aggregation_edges_resolved: count(types.aggregation_edges().len()),
        interaction_edges_resolved: count(types.interaction_edges().len()),
        use_targets_total,
        use_targets_resolved,
        use_targets_external,
        use_targets_unresolved,
        derives_seen,
        item_macros_seen,
        call_candidates_total: graph.resolved() + graph.unresolved(),
        call_candidates_resolved: graph.resolved(),
        call_candidates_external: graph.external(),
        call_candidates_unknown: graph.unknown_receiver()
    }
}

/// Lists the `use` targets [`coverage_with`] counts as unresolved — not
/// resolvable in-workspace and not attributable to a known external
/// crate — keyed by target path with occurrence counts.
///
/// This is the inspectable form of the coverage report's "unresolved"
/// bucket: it shows exactly which import shapes the engine does not yet
/// understand.
#[must_use]
pub fn unresolved_targets(
    sources: &[Source],
    external_crates: &BTreeSet<String>
) -> BTreeMap<String, u64> {
    let graph = ModuleGraph::from_sources(sources);
    let modules = graph.modules();
    let mut targets = BTreeMap::new();
    for (from, module) in modules.iter().enumerate() {
        for use_target in &module.uses {
            if resolved_module(modules, from, &use_target.target).is_none()
                && !external_target(&use_target.target, external_crates)
            {
                *targets.entry(use_target.target.clone()).or_default() += 1;
            }
        }
    }
    targets
}

/// Returns whether a `use` target's leading segment names a known external
/// crate: the standard-library family or a declared dependency.
fn external_target(target: &str, external_crates: &BTreeSet<String>) -> bool {
    const BUILTIN: [&str; 5] = ["alloc", "core", "proc_macro", "std", "test"];
    let first = target.split("::").next().unwrap_or(target);
    BUILTIN.contains(&first) || external_crates.contains(first)
}

/// Converts a collection length into a saturating `u64` counter.
fn count(value: usize) -> u64 {
    u64::try_from(value).unwrap_or(u64::MAX)
}

/// Syntax visitor counting derive attributes and item-level macro
/// invocations of one parsed file.
#[derive(Default)]
struct MacroCounter {
    /// `#[derive(...)]` attributes seen so far.
    derives:     u64,
    /// Item-level macro invocations seen so far.
    item_macros: u64
}

impl<'ast> Visit<'ast> for MacroCounter {
    fn visit_attribute(&mut self, attribute: &'ast syn::Attribute) {
        if attribute.path().is_ident("derive") {
            self.derives += 1;
        }
        syn::visit::visit_attribute(self, attribute);
    }

    fn visit_item_macro(&mut self, item: &'ast syn::ItemMacro) {
        self.item_macros += 1;
        syn::visit::visit_item_macro(self, item);
    }
}

#[cfg(test)]
#[allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    reason = "test code is allowed to fail loudly on broken invariants"
)]
mod tests {
    use std::{collections::BTreeSet, path::PathBuf};

    use super::{coverage, coverage_with, percent, unresolved_targets};
    use crate::source::Source;

    fn source(path: &str, text: &str) -> Source {
        Source::new(PathBuf::from(path), text.to_owned())
    }

    fn close(left: f64, right: f64) -> bool {
        (left - right).abs() < 1e-9
    }

    #[test]
    fn parse_failure_is_counted() {
        let sources = [
            source("src/lib.rs", "pub struct Ok;"),
            source("src/broken.rs", "fn broken(")
        ];
        let report = coverage(&sources);
        assert_eq!(report.files_total, 2);
        assert_eq!(report.files_parsed, 1);
        assert!(close(report.parse_rate(), 50.0));
    }

    #[test]
    fn unreachable_file_lowers_reachability() {
        let sources = [
            source("src/lib.rs", "mod util;"),
            source("src/util.rs", ""),
            source("src/orphan.rs", "")
        ];
        let report = coverage(&sources);
        assert_eq!(report.files_total, 3);
        assert_eq!(report.modules_total, 3);
        assert_eq!(report.files_reachable, 2);
        assert_eq!(report.files_standalone, 1);
        assert!(close(report.reachability_rate(), 200.0 / 3.0));
    }

    #[test]
    fn inline_modules_count_as_modules_of_one_file() {
        let sources = [source("src/lib.rs", "mod a {} mod b {}")];
        let report = coverage(&sources);
        assert_eq!(report.modules_total, 3);
        assert_eq!(report.files_reachable, 1);
    }

    #[test]
    fn lone_files_become_standalone_roots() {
        let sources = [source("rules/one.rs", ""), source("rules/two.rs", "")];
        let report = coverage(&sources);
        assert_eq!(report.modules_total, 2);
        assert_eq!(report.files_reachable, 0);
        assert_eq!(report.files_standalone, 2);
    }

    #[test]
    fn use_resolution_splits_workspace_and_external() {
        let sources = [
            source("src/lib.rs", "mod a; mod b;"),
            source("src/a.rs", "use crate::b::Item; use std::fmt;"),
            source("src/b.rs", "")
        ];
        let report = coverage(&sources);
        assert_eq!(report.use_targets_total, 2);
        assert_eq!(report.use_targets_resolved, 1);
        assert_eq!(report.use_targets_external, 1);
        assert_eq!(report.use_targets_unresolved, 0);
        assert!(close(report.resolution_rate(), 50.0));
        assert!(close(report.accounted_rate(), 100.0));
    }

    #[test]
    fn uniform_paths_to_child_modules_resolve_in_workspace() {
        let sources = [
            source("src/lib.rs", "mod handlers; pub use handlers::routes;"),
            source(
                "src/handlers.rs",
                "mod account; pub use account::account_routes; use serde::Serialize;"
            ),
            source("src/handlers/account.rs", "")
        ];
        let report = coverage(&sources);
        assert_eq!(report.use_targets_resolved, 2);
        assert_eq!(report.use_targets_unresolved, 1);
        let targets = unresolved_targets(&sources, &BTreeSet::new());
        assert_eq!(targets.len(), 1);
        assert_eq!(targets["serde::Serialize"], 1);
    }

    #[test]
    fn declared_dependencies_move_targets_from_unresolved_to_external() {
        let sources = [source(
            "src/lib.rs",
            "use serde::Serialize; use unknown_crate::Thing;"
        )];
        let bare = coverage(&sources);
        assert_eq!(bare.use_targets_external, 0);
        assert_eq!(bare.use_targets_unresolved, 2);
        let declared = BTreeSet::from(["serde".to_owned()]);
        let informed = coverage_with(&sources, &declared);
        assert_eq!(informed.use_targets_external, 1);
        assert_eq!(informed.use_targets_unresolved, 1);
        assert!(close(informed.accounted_rate(), 50.0));
    }

    #[test]
    fn type_graph_counters_are_reported() {
        let sources = [
            source("src/lib.rs", "pub struct Identity { pub id: u64 }"),
            source(
                "src/user.rs",
                "pub struct User { pub identity: Identity, pub age: u8 }"
            )
        ];
        let report = coverage(&sources);
        assert_eq!(report.structs_captured, 2);
        assert_eq!(report.fields_captured, 3);
        assert_eq!(report.aggregation_edges_resolved, 1);
    }

    #[test]
    fn derives_and_item_macros_are_counted() {
        let sources = [source(
            "src/lib.rs",
            "#[derive(Debug, Clone)]\npub struct A;\nmacro_rules! noise { () => {} }\nmod inner \
             { #[derive(Default)] pub struct B; }"
        )];
        let report = coverage(&sources);
        assert_eq!(report.derives_seen, 2);
        assert_eq!(report.item_macros_seen, 1);
    }

    #[test]
    fn empty_slice_yields_zero_rates() {
        let report = coverage(&[]);
        assert_eq!(report.files_total, 0);
        assert!(close(report.parse_rate(), 0.0));
        assert!(close(report.resolution_rate(), 0.0));
        assert!(close(report.reachability_rate(), 0.0));
    }

    #[test]
    fn percent_handles_zero_whole() {
        assert!(close(percent(1, 2), 50.0));
        assert!(close(percent(0, 0), 0.0));
        assert!(close(percent(3, 0), 0.0));
    }

    #[test]
    fn measurement_is_deterministic() {
        let sources = [
            source(
                "src/lib.rs",
                "mod a; #[derive(Debug)] pub struct S { f: u8 }"
            ),
            source("src/a.rs", "use crate::S; use std::fmt;")
        ];
        assert_eq!(coverage(&sources), coverage(&sources));
    }
}
